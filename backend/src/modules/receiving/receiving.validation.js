import { z } from "zod";
import { DISCREPANCY_TYPES, RECEIPT_STATUS } from "./receiving.constants.js";
import { optionalQueryValue } from "../../shared/http/query-validation.js";

const uuid = z.string().uuid();

const quantity = z
  .string()
  .regex(/^(?:0|[1-9]\d{0,9})(?:\.\d{1,2})?$/, "Quantity must be a plain decimal with at most two decimal places.");

const receiptLineSchema = z
  .object({
    dcLineId: uuid,
    receivedQuantity: quantity,
    discrepancyQuantity: quantity.optional().default("0"),
    discrepancyType: z.enum(DISCREPANCY_TYPES).nullable().optional(),
    discrepancyNote: z.string().trim().max(1000).nullable().optional(),
  })
  .strict()
  .refine((line) => Number(line.receivedQuantity) + Number(line.discrepancyQuantity) > 0, {
    message: "A receipt line must record a received or a discrepancy quantity.",
    path: ["receivedQuantity"],
  })
  .refine((line) => (Number(line.discrepancyQuantity) > 0) === Boolean(line.discrepancyType), {
    message: "A discrepancy quantity must name its discrepancy type, and vice versa.",
    path: ["discrepancyType"],
  });

export const recordReceiptSchema = z
  .object({
    // Stable per LOGICAL receipt, generated by the client before it sends.
    // A retry of the same request carries the same value and is answered with
    // the receipt that already exists; a genuinely separate partial receipt
    // carries a new one. Required, so no write is ever unprotected.
    operationId: uuid,
    // Temporary Admin custody is an explicit, separately authorized act —
    // never something ordinary department receiving falls into silently.
    fallback: z.boolean().optional().default(false),
    // Optional: the real person who physically took delivery when they have
    // no ESDMS login. The acting user is always the authenticated actor;
    // this never forges an actor identity.
    physicalReceiverEmployeeId: uuid.nullable().optional(),
    note: z.string().trim().max(1000).nullable().optional(),
    lines: z.array(receiptLineSchema).min(1).max(200),
  })
  .strict()
  .refine((data) => new Set(data.lines.map((line) => line.dcLineId)).size === data.lines.length, {
    message: "A Delivery Challan line cannot be received twice in one receipt.",
    path: ["lines"],
  });

export const receivingQueueQuerySchema = z
  .object({
    departmentId: optionalQueryValue(uuid),
    search: optionalQueryValue(z.string().trim().max(100)),
    page: optionalQueryValue(z.coerce.number().int().min(1).max(10_000)).default(1),
    pageSize: optionalQueryValue(z.coerce.number().int().min(1).max(100)).default(20),
  })
  .strict();

export const receiptListQuerySchema = receivingQueueQuerySchema.extend({
  status: optionalQueryValue(z.enum(Object.values(RECEIPT_STATUS))),
});
